#!/usr/bin/env python3
"""Write RQ2 search-space species clustering medians table (descriptive).

Reads ``rq2_run_level.csv``; writes ``notes/rough_draft/rq2_clustering_table.tex``.
"""

from __future__ import annotations

import csv
import statistics as st
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

ROOT = Path(__file__).resolve().parents[4]
CSV = ROOT / "experiments/evostar_2027/rq2/reports/rq2_run_level.csv"
OUT = ROOT / "notes/rough_draft/rq2_clustering_table.tex"

ORDER: List[Tuple[str, str]] = [
    ("embedding", "leader_follower"),
    ("embedding", "dbscan"),
    ("nli_entail", "leader_follower"),
    ("nli_entail", "dbscan"),
]
DIST_TEX = {"embedding": r"$d_E$", "nli_entail": r"$d_{\neg E}$"}
CLUS_TEX = {"leader_follower": "LF", "dbscan": "IncDBSCAN"}


def _f(row: Dict[str, str], key: str) -> float:
    try:
        return float(row[key])
    except (KeyError, TypeError, ValueError):
        return float("nan")


def _med(vals: Sequence[float]) -> float:
    ok = [v for v in vals if v == v]
    return float(st.median(ok)) if ok else float("nan")


def _fmt(v: float, nd: int = 2, intish: bool = False) -> str:
    if v != v:
        return "---"
    if intish:
        return str(int(round(v)))
    return f"{v:.{nd}f}"


def main() -> int:
    by: Dict[Tuple[str, str], List[Dict[str, str]]] = defaultdict(list)
    with CSV.open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            by[(r["distance"], r["clustering"])].append(r)

    body = []
    footnotes = []
    for d, c in ORDER:
        rs = by[(d, c)]
        nsp = [_f(r, "n_species") for r in rs]
        inter = [_f(r, "inter_diversity") for r in rs]
        intra = [_f(r, "intra_diversity") for r in rs]
        sil = []
        for r in rs:
            v = _f(r, "silhouette")
            if v != v:
                v = _f(r, "silhouette_common")
            sil.append(v)
        db = [_f(r, "davies_bouldin") for r in rs]
        ch = [_f(r, "calinski_harabasz") for r in rs]
        ratio = [
            (a / b) if (a == a and b == b and b > 0) else float("nan")
            for a, b in zip(inter, intra)
        ]
        n_ok = min(sum(v == v for v in inter), sum(v == v for v in sil))
        mark = ""
        if n_ok < 10:
            mark = r"$^{\dagger}$"
            footnotes.append(
                rf"$^{{\dagger}}$For {DIST_TEX[d]} {CLUS_TEX[c]}, Inter, Inter/Intra, Sil., DB, and CH "
                rf"use the ${n_ok}/10$ runs with $\ge 2$ mature species; Intra uses all $10$ runs. "
                rf"Inter/Intra is the median of the run-level ratios."
            )
        body.append(
            " & ".join(
                [
                    DIST_TEX[d],
                    CLUS_TEX[c] + mark,
                    _fmt(_med(nsp), 1) if _med(nsp) % 1 else _fmt(_med(nsp), intish=True),
                    _fmt(_med(inter), 3),
                    _fmt(_med(intra), 3),
                    _fmt(_med(ratio), 1),
                    _fmt(_med(sil), 2),
                    _fmt(_med(db), 2),
                    _fmt(_med(ch), 1),
                ]
            )
            + r" \\"
        )

    note = " ".join(footnotes) if footnotes else ""
    tex = f"""% RQ2 search-space species clustering (descriptive medians).
% Auto-generated by experiments/evostar_2027/rq2/scripts/rq2_clustering_table.py
\\begin{{table}}[ht]
\\centering
\\caption{{RQ2 endpoint population structure (medians over $n{{=}}10$ runs; indices in MiniLM space).
{note}}}
\\label{{tab:rq2-clustering}}
\\scriptsize
\\setlength{{\\tabcolsep}}{{3.5pt}}
\\begin{{tabular}}{{@{{}}llccccccc@{{}}}}
\\toprule
Dissim. & Method & $n_{{\\mathrm{{mat}}}}$ & Inter & Intra & Inter/Intra & Sil. & DB & CH \\\\
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    OUT.write_text(tex, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
